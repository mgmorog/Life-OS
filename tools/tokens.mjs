// npm run tokens — reads the :root tokens in src/style.css and writes
//   TOKENS.md                    a grouped table of every token, for people
//   design-system/tokens.json    the Life OS design system's tokens (the Design System artifact reads this shape)
// Usage notes and type styles already in design-system/tokens.json are kept; values always come from style.css.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
const root = new URL('..', import.meta.url).pathname;
const css = readFileSync(root + 'src/style.css', 'utf8');
const m = /:root\{([\s\S]*?)\n\}/.exec(css);
if (!m) { console.error('No :root block in src/style.css'); process.exit(1); }

// groups come from the /* … */ headings inside :root
const groups = []; let cur = null;
for (const raw of m[1].split('\n')) {
  const line = raw.trim();
  const h = /^\/\*\s*(.+?)\s*\*\/$/.exec(line);
  if (h) { cur = { title: h[1], tokens: [] }; groups.push(cur); continue; }
  for (const d of line.split(/;(?![^(]*\))/)) {
    const mm = /^\s*(--[\w-]+)\s*:\s*(.+?)\s*$/.exec(d);
    if (mm && cur) cur.tokens.push([mm[1].slice(2), mm[2]]);
  }
}
const all = new Map(groups.flatMap(g => g.tokens));
const resolve = (v, depth = 0) => v.replace(/var\(--([\w-]+)\)/g, (_, n) => depth > 8 || !all.has(n) ? `var(--${n})` : resolve(all.get(n), depth + 1));

// TOKENS.md
let md = '# Life OS tokens\n\nGenerated by `npm run tokens` from `src/style.css`. Do not edit by hand: change the `:root` block and rerun.\n\nComponents use the **Roles**; palettes in Settings change the accent colours underneath them.\n';
for (const g of groups) {
  md += `\n## ${g.title}\n\n| Token | Value | Resolves to |\n| --- | --- | --- |\n`;
  for (const [n, v] of g.tokens) { const r = resolve(v); md += `| \`--${n}\` | \`${v.replace(/\|/g, '\\|')}\` | ${r !== v ? '`' + r.replace(/\|/g, '\\|') + '`' : ''} |\n`; }
}
writeFileSync(root + 'TOKENS.md', md);

// design-system/tokens.json
const out = root + 'design-system/tokens.json';
const prev = existsSync(out) ? JSON.parse(readFileSync(out, 'utf8')) : {};
const usage = new Map();
for (const fam of Object.values(prev)) if (fam && Array.isArray(fam.tokens)) for (const t of fam.tokens) if (t.usage) usage.set(t.name, t.usage);
const isColor = v => /^(#[0-9a-f]{3,8}|rgba?\(|hsla?\()/i.test(v);
const fam = (names, pick) => ({ tokens: [...all].filter(([n]) => pick(n)).map(([n, v]) => ({ name: n, value: resolve(v), ...(usage.get(n) ? { usage: usage.get(n) } : {}) })) });
const colorTokens = [...all].filter(([n, v]) => isColor(resolve(v)) && !/^(shadow|e-)/.test(n)).map(([n, v]) => {
  const alias = /^var\(--([\w-]+)\)$/.exec(v);
  return { name: n, value: alias && isColor(resolve(v)) ? `{${alias[1]}}` : resolve(v), ...(usage.get(n) ? { usage: usage.get(n) } : {}) };
});
const ds = {
  name: 'Life OS', version: (prev.version || 0) + 1,
  meta: { source: 'github.com/Mgmorog/life-os · src/style.css :root', generated: new Date().toISOString() },
  color: { themes: [{ id: 'light', name: 'Light' }], tokens: colorTokens },
  type: prev.type || {},
  spacing: fam(0, n => /^s\d$/.test(n)),
  radius: fam(0, n => /^r-/.test(n)),
  shadow: fam(0, n => /^e-(raised|floating|overlay|focus)$/.test(n)),
  zIndex: fam(0, n => /^z-/.test(n)),
  opacity: fam(0, n => /^o-/.test(n)),
  state: fam(0, n => /^(press|press-row|focus-w)$/.test(n)),
  control: fam(0, n => /^(ctl|ctl-sm|ctl-lg|row-2)$/.test(n)),
  icon: fam(0, n => /^icon(-sm|-md|-lg)?$/.test(n)),
  lineHeight: fam(0, n => /^lh-/.test(n)),
  duration: fam(0, n => /^dur-/.test(n)),
};
for (const [k, v] of Object.entries(ds)) if (v && Array.isArray(v.tokens) && k !== 'color') v.tokens = v.tokens.filter(t => /^[A-Za-z0-9 #%(),./+_-]{1,200}$/.test(String(t.value)));
mkdirSync(root + 'design-system', { recursive: true });
writeFileSync(out, JSON.stringify(ds, null, 1) + '\n');
console.log(`tokens: ${all.size} in ${groups.length} groups → TOKENS.md, design-system/tokens.json (${colorTokens.length} colours)`);
